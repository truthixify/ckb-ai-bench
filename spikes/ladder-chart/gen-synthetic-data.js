// Spike (NOT production): generator for the ladder chart's SYNTHETIC dataset.
// Writes synthetic-results.json with an explicit _SYNTHETIC marker so fabricated
// numbers can NEVER be mistaken for a real benchmark run. No deps.
//
// Shape it produces (one row per cell = model x chain x arm):
//   { model, family, chain, arm, runs, mean, ci_low, ci_high }
// where arm in A/B/C/D, chain in devnet/testnet, mean = Pass@1 in [0,1].
//
// Deliberate headline (C - B) cases so the HONESTY of the rendering is testable:
//   - Opus       : strong POSITIVE C-B  (MCP clearly helps)
//   - Grok-Build : ~FLAT     C-B  (MCP adds nothing)
//   - GPT-5.5    : slightly NEGATIVE C-B (MCP hurts a touch)
// The other three are ordinary positive/mixed lines.

'use strict';

const fs = require('fs');
const path = require('path');

// Six models across three families (ADR-0011: one line per model, color by family).
const MODELS = [
  { model: 'Sonnet', family: 'Anthropic' },
  { model: 'Opus', family: 'Anthropic' },
  { model: 'Fable', family: 'Anthropic' },
  { model: 'Grok-Build', family: 'xAI' },
  { model: 'Grok-Compose', family: 'xAI' },
  { model: 'GPT-5.5', family: 'OpenAI' },
];

const CHAINS = ['devnet', 'testnet'];
const RUNS_PER_CELL = 3; // matches the design: 3 runs/cell -> wide CIs, always shown.

// Per-model arm means on DevNet. Hand-set so the three load-bearing headline
// shapes are unambiguous. TestNet is derived as a small offset of DevNet below,
// but kept as its own separate score (never merged).
// Means are Pass@1 in [0,1].
const DEVNET_MEANS = {
  // strong positive C-B (0.78 - 0.52 = +0.26)
  Opus: { A: 0.30, B: 0.52, C: 0.78, D: 0.66 },
  // flat C-B (0.61 - 0.60 = +0.01)
  'Grok-Build': { A: 0.34, B: 0.60, C: 0.61, D: 0.55 },
  // slightly negative C-B (0.49 - 0.53 = -0.04)
  'GPT-5.5': { A: 0.28, B: 0.53, C: 0.49, D: 0.47 },
  // ordinary positive lines
  Sonnet: { A: 0.26, B: 0.44, C: 0.63, D: 0.55 },
  Fable: { A: 0.22, B: 0.40, C: 0.58, D: 0.50 },
  'Grok-Compose': { A: 0.31, B: 0.50, C: 0.60, D: 0.52 },
};

// TestNet differs from DevNet (separate score). Apply a fixed per-arm offset so
// the two chains are visibly distinct lines, NOT a copy. testnet is a touch lower
// and noisier (live-ops track), which is realistic and keeps them un-mergeable.
const TESTNET_ARM_OFFSET = { A: -0.04, B: -0.06, C: -0.05, D: -0.07 };

function clamp01(x) {
  return Math.max(0, Math.min(1, x));
}

// CI half-width for a 3-run cell. Deliberately WIDE (the design mandates visible
// CIs at n=3). Scale it with binomial-ish spread so means near 0.5 get the widest
// band; floor it so even extreme means keep a visible band.
function ciHalfWidth(mean) {
  const spread = Math.sqrt(clamp01(mean) * (1 - clamp01(mean)) / RUNS_PER_CELL);
  return Math.max(0.07, 1.15 * spread); // ~0.07..0.33; always visible
}

function makeCell(model, family, chain, arm, mean) {
  const m = clamp01(mean);
  const h = ciHalfWidth(m);
  return {
    model,
    family,
    chain,
    arm,
    runs: RUNS_PER_CELL,
    mean: round(m),
    ci_low: round(clamp01(m - h)),
    ci_high: round(clamp01(m + h)),
  };
}

function round(x) {
  return Math.round(x * 1000) / 1000;
}

function build() {
  const cells = [];
  for (const { model, family } of MODELS) {
    const dev = DEVNET_MEANS[model];
    for (const arm of ['A', 'B', 'C', 'D']) {
      // DevNet
      cells.push(makeCell(model, family, 'devnet', arm, dev[arm]));
      // TestNet = separate score, offset from DevNet
      cells.push(makeCell(model, family, 'testnet', arm, dev[arm] + TESTNET_ARM_OFFSET[arm]));
    }
  }
  return {
    _SYNTHETIC: true,
    _WARNING: 'SYNTHETIC FABRICATED DATA - NOT a real benchmark run. Generated by gen-synthetic-data.js to de-risk the ADR-0011 reporting pipeline. Do NOT cite as results.',
    generated_at: new Date().toISOString(),
    generator: 'spikes/ladder-chart/gen-synthetic-data.js',
    schema: {
      score: 'Pass@1 in [0,1]',
      arms: { A: 'no MCP, no web (floor)', B: 'web research, no MCP', C: 'MCP + web', D: 'MCP, no web (diagnostic)' },
      headline: 'C - B = MCP marginal value over ordinary web research (ADR-0011)',
      chains: 'devnet and testnet are SEPARATE scores, never merged',
      runs_per_cell: RUNS_PER_CELL,
      ci: 'ci_low/ci_high bound the mean; wide at n=3 by design, always shown',
    },
    families: Array.from(new Set(MODELS.map((m) => m.family))),
    models: MODELS.map((m) => m.model),
    chains: CHAINS,
    cells,
  };
}

function main() {
  const out = build();
  const outPath = path.join(__dirname, 'synthetic-results.json');
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n');
  process.stderr.write(
    `wrote ${out.cells.length} synthetic cells (${out.models.length} models x ${out.chains.length} chains x 4 arms) -> ${outPath}\n`
  );
}

if (require.main === module) main();

module.exports = { build, MODELS, CHAINS, DEVNET_MEANS, TESTNET_ARM_OFFSET };
